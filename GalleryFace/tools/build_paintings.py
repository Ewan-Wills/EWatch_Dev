#!/usr/bin/env python3
"""Pack Claire Wills paintings into src/paintings_data.h as baseline JPEGs.

Source: the clairewills.co.uk SQLite database (Work table; originals only,
prints and cards are copies of originals). Every painting is scaled to the
watch width (240 px), centre-cropped to at most MAX_H tall, and JPEG-encoded
at ONE shared quality, the highest that fits BUDGET bytes. Duplicate images
(same painting uploaded twice) are dropped by a tiny-thumbnail hash.

  uv run --with pillow tools/build_paintings.py [path/to/db.sqlite] [--budget N]
"""
import argparse, hashlib, re, io, random, sqlite3, sys
from pathlib import Path
from PIL import Image

W, MAX_H, MIN_H = 240, 360, 80

def shown_title(t):
    """Upload filenames ("00_ce", "2022-08-ZQ2X9586-1") are not titles: hide them."""
    t = (t or "").strip()
    return "" if re.match(r"^(\d|IMG|DSC|ZQ)", t) or "_" in t else t

ap = argparse.ArgumentParser()
ap.add_argument("db", nargs="?", default=str(Path.home() / "Documents/clairewillswebsite/db.sqlite"))
ap.add_argument("--budget", type=int, default=3_740_000, help="bytes of JPEG data (4128768 B app partition - ~370 KB code - margin)")
ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "src/paintings_data.h"))
a = ap.parse_args()

con = sqlite3.connect(f"file:{a.db}?mode=ro", uri=True)
rows = con.execute("SELECT id, title, img FROM Work WHERE coalesce(isPrint,0)=0 "
                   "AND coalesce(isCard,0)=0 ORDER BY id").fetchall()
print(f"{len(rows)} originals in {a.db}")

imgs, seen = [], set()
for wid, title, blob in rows:
    try:
        im = Image.open(io.BytesIO(blob)); im.load()
    except Exception as e:
        print(f"  skip {wid} {title!r}: {e}"); continue
    im = im.convert("RGB")
    h = max(MIN_H, round(im.height * W / im.width))
    im = im.resize((W, h), Image.LANCZOS)
    if h > MAX_H:
        top = (h - MAX_H) // 2
        im = im.crop((0, top, W, top + MAX_H))
    key = hashlib.md5(im.resize((12, 12)).convert("L").tobytes()).hexdigest()
    if key in seen:
        print(f"  dup  {wid} {title!r}"); continue
    seen.add(key); imgs.append((wid, title, im))
print(f"{len(imgs)} unique paintings")

def encode(q):
    out = []
    for _, _, im in imgs:
        b = io.BytesIO()
        im.save(b, "JPEG", quality=q, optimize=True, progressive=False, subsampling=2)
        out.append(b.getvalue())
    return out

lo, hi, best = 10, 90, None
while lo <= hi:                       # highest quality that fits
    q = (lo + hi) // 2; enc = encode(q); total = sum(map(len, enc))
    print(f"  q={q}: {total/1e6:.2f} MB")
    if total <= a.budget: best = (q, enc); lo = q + 1
    else: hi = q - 1
if not best:                          # even q=10 too big: drop images
    sys.exit("does not fit even at q=10; lower MAX_H or the count")
q, enc = best

order = list(range(len(imgs))); random.Random(7).shuffle(order)   # mix years/series
blob, index = bytearray(), []
for i in order:
    wid, title, im = imgs[i]
    index.append((len(blob), len(enc[i]), im.height, shown_title(title))); blob += enc[i]

def cstr(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"').encode("ascii", "replace").decode() + '"'
with open(a.out, "w") as f:
    f.write(f"// Auto-generated by tools/build_paintings.py from {Path(a.db).name}. Do not edit.\n")
    f.write(f"// {len(index)} paintings by Claire Wills, 240 px wide baseline JPEG, quality {q}, {len(blob)} bytes.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write("struct Painting { uint32_t off; uint32_t len; uint16_t h; const char *title; };\n")
    f.write(f"static const uint16_t PAINTING_COUNT = {len(index)};\n")
    f.write("static const uint8_t PAINTING_JPEG[] = {\n")
    for i in range(0, len(blob), 32):
        f.write("".join(f"{x}," for x in blob[i:i+32]) + "\n")
    f.write("};\nstatic const Painting PAINTINGS[] = {\n")
    for off, ln, h, t in index:
        f.write(f"  {{{off}, {ln}, {h}, {cstr(t)}}},\n")
    f.write("};\n")
Path(a.out).with_suffix(".txt").write_text("\n".join(t for *_, t in index) + "\n")
print(f"wrote {a.out}: {len(index)} paintings, q={q}, {len(blob)/1e6:.2f} MB, avg {len(blob)//len(index)} B")
