"""Build EWatchOS' default background (Photo face fallback + screensaver) from
a painting: portrait crop -> 240x280 -> RGB565 with Floyd-Steinberg dither.

  uv run --with pillow --with numpy tools/default_bg/gen_default_bg.py [--x0 N]

Writes src/apps/assets/default_bg_data.inc and tools/default_bg/preview.png
(the RGB565 result, as the panel will show it).
"""
import argparse, os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
W, H = 240, 280

ap = argparse.ArgumentParser()
ap.add_argument("--src", default=os.path.join(HERE, "neist_point.webp"))
ap.add_argument("--x0", type=int, default=None, help="left edge of the crop in source px")
a = ap.parse_args()

img = Image.open(a.src).convert("RGB")
sw, sh = img.size
cw = round(sh * W / H)                      # full source height, screen aspect
x0 = a.x0 if a.x0 is not None else (sw - cw) // 2
x0 = max(0, min(sw - cw, x0))
crop = img.crop((x0, 0, x0 + cw, sh)).resize((W, H), Image.LANCZOS)

# Floyd-Steinberg to 5-6-5 so the sky gradients don't band.
px = np.asarray(crop, dtype=np.float32).copy()
levels = np.array([31, 63, 31], dtype=np.float32)
out = np.zeros((H, W), dtype=np.uint16)
prev = np.zeros((H, W, 3), dtype=np.uint8)
for y in range(H):
    for x in range(W):
        old = np.clip(px[y, x], 0, 255)
        q = np.round(old / 255 * levels)
        new = q / levels * 255
        err = old - new
        r, g, b = (int(v) for v in q)
        out[y, x] = (r << 11) | (g << 5) | b
        prev[y, x] = new.astype(np.uint8)
        if x + 1 < W: px[y, x + 1] += err * 7 / 16
        if y + 1 < H:
            if x > 0: px[y + 1, x - 1] += err * 3 / 16
            px[y + 1, x] += err * 5 / 16
            if x + 1 < W: px[y + 1, x + 1] += err * 1 / 16

Image.fromarray(prev).save(os.path.join(HERE, "preview.png"))
lines = [
    f"// Generated by tools/default_bg/gen_default_bg.py from {os.path.basename(a.src)}",
    f"// (crop x0={x0} w={cw} of {sw}x{sh}, LANCZOS -> {W}x{H}, Floyd-Steinberg RGB565). Do not edit.",
    f"const uint16_t DEFAULT_BG[{W * H}] = {{",
]
flat = out.ravel()
for i in range(0, flat.size, 12):
    lines.append("  " + ",".join(f"0x{v:04X}" for v in flat[i:i + 12]) + ",")
lines.append("};")
open(os.path.join(ROOT, "src/apps/assets/default_bg_data.inc"), "w").write("\n".join(lines) + "\n")
print(f"source {sw}x{sh}, crop x0={x0} w={cw} -> {W}x{H}; wrote default_bg_data.inc + preview.png")
