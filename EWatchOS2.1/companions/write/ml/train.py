"""Train the Write CNN, fold BN, quantise weights to int8, export a C header.

usage: train.py [epochs] [out_header]
Prints accuracy of the float model AND of the int8 reference (ref_infer,
the same arithmetic as write_cnn.cpp) on the unseen UJI writers.
"""
import sys, time
import numpy as np
import torch, torch.nn as nn, torch.nn.functional as F
from common import CLASSES

dev = "mps" if torch.backends.mps.is_available() else "cpu"
torch.manual_seed(0)
import os
C1, C2, C3, FC = (int(v) for v in os.environ.get("WCNN", "16,32,64,128").split(","))
CASE = os.environ.get("WCASE") == "1"     # 62 classes (a-z separate), merged to 36 at the end
NC = 62 if CASE else len(CLASSES)
TRAIN = os.environ.get("WTRAIN", "data/train.npz")


class Net(nn.Module):
    def __init__(s):
        super().__init__()
        s.c1 = nn.Conv2d(1, C1, 3, padding=1, bias=False); s.b1 = nn.BatchNorm2d(C1)
        s.c2 = nn.Conv2d(C1, C2, 3, padding=1, bias=False); s.b2 = nn.BatchNorm2d(C2)
        s.c3 = nn.Conv2d(C2, C3, 3, padding=1, bias=False); s.b3 = nn.BatchNorm2d(C3)
        s.f1 = nn.Linear(C3 * 9, FC); s.f2 = nn.Linear(FC, NC); s.dp = nn.Dropout(0.3)

    def forward(s, x):
        x = F.max_pool2d(F.relu(s.b1(s.c1(x))), 2)      # 14
        x = F.max_pool2d(F.relu(s.b2(s.c2(x))), 2)      # 7
        x = F.max_pool2d(F.relu(s.b3(s.c3(x))), 2)      # 3
        return s.f2(s.dp(F.relu(s.f1(x.flatten(1)))))


def gpu_aug(x):
    n = x.shape[0]
    th = (torch.rand(n, device=dev) - 0.5) * 2 * np.deg2rad(8)
    sc = 1 + (torch.rand(n, device=dev) - 0.5) * 0.2
    tx = (torch.rand(n, 2, device=dev) - 0.5) * 2 * (1.5 / 14)
    A = torch.zeros(n, 2, 3, device=dev)
    A[:, 0, 0] = torch.cos(th) / sc; A[:, 0, 1] = -torch.sin(th) / sc
    A[:, 1, 0] = torch.sin(th) / sc; A[:, 1, 1] = torch.cos(th) / sc
    A[:, :, 2] = tx
    g = F.affine_grid(A, x.shape, align_corners=False)
    return F.grid_sample(x, g, align_corners=False)


def load(p, key="y"):
    d = np.load(p)
    return torch.tensor(d["x"]).float().div(255).unsqueeze(1), torch.tensor(d[key]).long()


def merge36(p):
    """probabilities (n,NC) -> (n,36): lower-case letters add to their upper."""
    if p.shape[1] == 36:
        return p
    q = p[:, :36].clone() if torch.is_tensor(p) else p[:, :36].copy()
    q[:, :26] += p[:, 36:62]
    return q


def evaluate(m, X, Y):
    m.eval(); out = []
    with torch.no_grad():
        for i in range(0, len(X), 4096):
            out.append(m(X[i:i + 4096].to(dev)).cpu())
    lo = merge36(torch.cat(out).softmax(1))
    top3 = lo.topk(3, 1).indices
    return (lo.argmax(1) == Y).float().mean().item(), (top3 == Y[:, None]).any(1).float().mean().item()


# ---------------------------------------------------------------- export
def fold(conv, bn):
    w = conv.weight.detach().cpu().numpy()
    g = (bn.weight / torch.sqrt(bn.running_var + bn.eps)).detach().cpu().numpy()
    b = (bn.bias - bn.running_mean * bn.weight / torch.sqrt(bn.running_var + bn.eps)).detach().cpu().numpy()
    return w * g[:, None, None, None], b


def q8(w):
    """Per-output-channel symmetric int8. -> (int8 array, float scales)."""
    flat = w.reshape(w.shape[0], -1)
    s = np.abs(flat).max(1) / 127.0
    s[s == 0] = 1
    q = np.clip(np.round(flat / s[:, None]), -127, 127).astype(np.int8)
    return q.reshape(w.shape), s.astype(np.float32)


def export(m):
    m.eval().cpu()
    L = {}
    for n, (c, b) in {"c1": (m.c1, m.b1), "c2": (m.c2, m.b2), "c3": (m.c3, m.b3)}.items():
        w, bias = fold(c, b)
        L[n] = (*q8(w), bias.astype(np.float32))
    for n, f in {"f1": m.f1, "f2": m.f2}.items():
        L[n] = (*q8(f.weight.detach().numpy()), f.bias.detach().numpy().astype(np.float32))
    m.to(dev)
    return L


def ref_infer(L, img):
    """img (28,28) float [0,1] -> logits. Same loops/order as write_cnn.cpp."""
    x = img[None].astype(np.float32)
    for n in ("c1", "c2", "c3"):
        q, s, b = L[n]
        w = q.astype(np.float32) * s[:, None, None, None]
        ci, H, W = x.shape
        p = np.pad(x, ((0, 0), (1, 1), (1, 1)))
        y = np.zeros((w.shape[0], H, W), np.float32)
        for ky in range(3):
            for kx in range(3):
                y += np.einsum("oc,chw->ohw", w[:, :, ky, kx], p[:, ky:ky + H, kx:kx + W])
        y = np.maximum(y + b[:, None, None], 0)
        H2, W2 = H // 2, W // 2
        x = y[:, :H2 * 2, :W2 * 2].reshape(w.shape[0], H2, 2, W2, 2).max((2, 4))
    v = x.reshape(-1)
    q, s, b = L["f1"]; v = np.maximum((q.astype(np.float32) * s[:, None]) @ v + b, 0)
    q, s, b = L["f2"]; return (q.astype(np.float32) * s[:, None]) @ v + b


def header(L, path, note):
    def arr(name, a, ty):
        vals = ",".join(str(int(v)) if ty == "int8_t" else f"{v:.8g}f" for v in a.ravel())
        return f"static const {ty} {name}[{a.size}] = {{{vals}}};\n"
    out = ["// GENERATED by ml-write/train.py - do not edit. " + note + "\n",
           "#pragma once\n#include <stdint.h>\nnamespace wcnn_w {\n",
           f"constexpr int C1 = {C1}, C2 = {C2}, C3 = {C3}, FC = {FC}, NC = {NC};\n",
           f'static const char kClassChars[] = "{CLASSES}";\n']
    for n, (q, s, b) in L.items():
        out += [arr(f"{n}_w", q, "int8_t"), arr(f"{n}_s", s, "float"), arr(f"{n}_b", b, "float")]
    out.append("}  // namespace wcnn_w\n")
    open(path, "w").write("".join(out))


def main():
    epochs = int(sys.argv[1]) if len(sys.argv) > 1 else 12
    hdr = sys.argv[2] if len(sys.argv) > 2 else "write_cnn_weights.h"
    Xtr, Ytr = load(TRAIN, "y62" if CASE else "y")
    for extra in filter(None, os.environ.get("WEXTRA", "").split(",")):   # e.g. data/fonts.npz
        Xe2, Ye2 = load(extra)
        Xtr, Ytr = torch.cat([Xtr, Xe2]), torch.cat([Ytr, Ye2])
        print("extra", extra, len(Ye2))
    Xu, Yu = load("data/test_uji.npz")
    Xe, Ye = load("data/test_emnist.npz")
    Xtr = Xtr.to(dev); Ytr = Ytr.to(dev)
    m = Net().to(dev)
    print("params", sum(p.numel() for p in m.parameters()))
    bs = 256
    steps = epochs * (len(Xtr) // bs)
    opt = torch.optim.AdamW(m.parameters(), 3e-3, weight_decay=1e-4)
    sch = torch.optim.lr_scheduler.OneCycleLR(opt, 3e-3, total_steps=steps)
    for ep in range(epochs):
        m.train(); t0 = time.time()
        perm = torch.randperm(len(Xtr), device=dev)
        for i in range(len(Xtr) // bs):
            j = perm[i * bs:(i + 1) * bs]
            x = gpu_aug(Xtr[j])
            loss = F.cross_entropy(m(x), Ytr[j], label_smoothing=0.1)
            opt.zero_grad(); loss.backward(); opt.step(); sch.step()
        u = evaluate(m, Xu, Yu); e = evaluate(m, Xe, Ye)
        print(f"ep {ep} loss {loss.item():.3f} uji-unseen top1 {u[0]:.4f} top3 {u[1]:.4f}  emnist {e[0]:.4f}/{e[1]:.4f}  {time.time()-t0:.0f}s", flush=True)
    torch.save(m.state_dict(), os.environ.get("WPT", "write_cnn.pt"))
    L = export(m)
    xs = Xu.squeeze(1).numpy()
    def p36(lo):
        e = np.exp(lo - lo.max()); return merge36((e / e.sum())[None])[0]
    pred = np.array([p36(ref_infer(L, xs[i])).argmax() for i in range(len(xs))])
    acc = (pred == Yu.numpy()).mean()
    print(f"int8 reference on unseen UJI writers: top1 {acc:.4f}")
    size = sum(q.size + 4 * s.size + 4 * b.size for q, s, b in L.values())
    print("weights bytes", size)
    # per-class misses
    cm = {}
    for p, y in zip(pred, Yu.numpy()):
        if p != y: cm[(CLASSES[y], CLASSES[p])] = cm.get((CLASSES[y], CLASSES[p]), 0) + 1
    print("top confusions (true->pred):", sorted(cm.items(), key=lambda kv: -kv[1])[:20])
    header(L, hdr, f"unseen-writer UJI int8 top1 {acc:.4f}, {size} bytes")


if __name__ == "__main__":
    main()
