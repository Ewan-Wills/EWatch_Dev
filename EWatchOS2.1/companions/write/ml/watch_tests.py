"""Turn real handwriting from UJIpenchars2 *test* writers (never used in
training) into finger draws on the watch's ink area.

  watch_tests.py samples OUT.txt          every tst glyph -> cnn_bench input
  watch_tests.py ewt OUT.ewt [PER]        the alphabet + digits, PER styles each
                                          (half upper-case, half lower-case
                                          writers), as an ewt script
  watch_tests.py score EWT_OUTPUT.txt OUT.ewt.labels

Placement: the glyph's longest side is scaled to 100-150 px, centred near
(120, 185) in the ink area (y >= 96), and each stroke is resampled every
8-14 px like the touch chip's ~30 ms reports.
"""
import sys
import numpy as np
from common import parse_uji, label_of, CLASSES

TWINS = [set("O0"), set("I1")]   # identical once box-normalised (when written plainly)


def place(strokes, r):
    pts = np.concatenate(strokes, 0)
    mn, mx = pts.min(0), pts.max(0)
    size = max(mx - mn)
    target = r.uniform(100, 150)
    s = target / max(size, 1e-6)
    c = (mn + mx) / 2
    centre = np.array([120 + r.uniform(-12, 12), 186 + r.uniform(-8, 8)])
    out = []
    for st in strokes:
        q = (st - c) * s + centre
        # resample every `step` px along the stroke (finger reports)
        step = r.uniform(10, 16)
        if len(q) > 1:
            seg = np.sqrt(((q[1:] - q[:-1]) ** 2).sum(1))
            cum = np.concatenate([[0], np.cumsum(seg)])
            L = cum[-1]
            k = max(2, int(L / step) + 1)
            t = np.linspace(0, L, k)
            q = np.stack([np.interp(t, cum, q[:, 0]), np.interp(t, cum, q[:, 1])], 1)
        q = np.round(q).astype(int)
        q[:, 0] = np.clip(q[:, 0], 4, 235)
        q[:, 1] = np.clip(q[:, 1], 100, 275)
        out.append(q)
    return out


def stroke_step(strokes, dt=30):
    """One ewsim `stroke` step for a whole glyph (pen lifts as |), real timing on
    the watch. Kept under the 320-char console line: coarser if needed."""
    for k in range(1, 6):
        parts = [" ".join(f"{x} {y}" for x, y in (list(q[:-1:k]) + [q[-1]] if len(q) > 2 else q)) for q in strokes]
        s = f"stroke {dt} " + " | ".join(parts)
        if len(s) < 270:
            return s
    return s


def tst():
    return [(label_of(ch), ch, w, s) for ch, w, s in parse_uji("data/uji/ujipenchars2.txt")
            if label_of(ch) is not None and w.startswith("tst")]


def samples(path):
    r = np.random.default_rng(7)
    with open(path, "w") as f:
        for lab, ch, w, s in tst():
            st = place(s, r)
            toks = [f"{x} {y} {i}" for i, q in enumerate(st) for x, y in q]
            f.write(f"{CLASSES[lab]} {len(toks)} {' '.join(toks)}\n")


def ewt(path, per):
    r = np.random.default_rng(11)
    data = tst()
    lines = ["# GENERATED by ml-write/watch_tests.py: UJIpenchars2 test writers (unseen in training)",
             "goto AppList", "wait 300", "goto Write", "wait 600", "expect screen Write"]
    labels = []
    for ch in CLASSES:
        if ch.isalpha():
            ups = [d for d in data if d[1] == ch]
            los = [d for d in data if d[1] == ch.lower()]
            pick = [ups[i] for i in r.choice(len(ups), per // 2, replace=False)] + \
                   [los[i] for i in r.choice(len(los), per - per // 2, replace=False)]
        else:
            ds = [d for d in data if d[1] == ch]
            pick = [ds[i] for i in r.choice(len(ds), per, replace=False)]
        for lab, orig, w, s in pick:
            labels.append(f"{CLASSES[lab]} {orig} {w}")
            lines.append(f"# {orig} by {w}")
            lines.append("goto Write")              # strokes must never land in another app
            lines.append("expect screen Write")     # (drive() splits glyphs at these two steps)
            lines.append("wait 150")
            lines.append(stroke_step(place(s, r)))
            lines.append("wait 900")
            lines.append("show WRITE: (char|reject|edit)")
            lines.append("long 210 250 800")        # hold delete: clear, no context from the previous glyph
    lines.append("expect noerr")
    open(path, "w").write("\n".join(lines) + "\n")
    open(path + ".labels", "w").write("\n".join(labels) + "\n")
    print(f"{len(labels)} glyphs, {sum(l.startswith('touch') for l in lines)} touch steps")


def score(out_path, labels_path):
    import re
    labels = [l.split() for l in open(labels_path).read().splitlines() if l.strip()]
    txt = open(out_path).read()
    if "== glyph" in txt:      # drive() output: one block per glyph, keep alignment
        blocks = txt.split("== glyph ")[1:]
        got = []
        for b in blocks:
            hits = [l for l in b.splitlines() if re.search(r"WRITE: (char|reject|edit)", l)]
            got.append(hits[-1] if hits else "WRITE: none (no recognition)")
    else:
        got = [l for l in txt.splitlines() if re.search(r"WRITE: (char|reject|edit)", l)]
    if len(got) != len(labels):
        print(f"WARNING: {len(got)} recognitions for {len(labels)} glyphs; scoring in order up to the shorter")
    n = ok = tw = top3 = 0
    misses = []
    ms = []
    for (want, orig, w), g in zip(labels, got):
        n += 1
        m = re.search(r"char=(\S) score=([\d.]+) ms=(\d+) cands=(\S+)", g)
        if not m:
            misses.append(f"{orig}({w}) -> {g.split('WRITE: ')[1][:40]}")
            continue
        c, cands = m.group(1), [x.split(":")[0] for x in m.group(4).split(",")]
        ms.append(int(m.group(3)))
        if c == want: ok += 1
        if c == want or any({c, want} <= t for t in TWINS): tw += 1
        else: misses.append(f"{orig}({w}) -> {c} [{m.group(4)}]")
        if want in cands: top3 += 1
    print(f"glyphs={n} top1={ok}/{n}={ok/max(n,1):.3f} twin-tolerant={tw}/{n}={tw/max(n,1):.3f} "
          f"top3={top3}/{n}={top3/max(n,1):.3f} ms mean={np.mean(ms) if ms else 0:.1f} max={max(ms) if ms else 0}")
    for x in misses: print("  miss:", x)
    return 0 if n == len(labels) and n > 0 else 1


if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "samples": samples(sys.argv[2])
    elif cmd == "ewt": ewt(sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 4)
    elif cmd == "score": sys.exit(score(sys.argv[2], sys.argv[3]))


def drive(ewt_cmd, script, outp):
    """Run an ewt script glyph by glyph (one `ewt do` each, one retry), so a
    lost console reply can't sink the sweep. Appends the ewt output to outp."""
    import subprocess
    lines = [l for l in open(script).read().splitlines() if l and not l.startswith("#")]
    first = lines.index("expect screen Write") + 1        # head: get into Write once
    head, glyphs = lines[:first], []
    for l in lines[first:]:
        if l == "goto Write":                                # each glyph starts here
            glyphs.append([])
        if glyphs and l != "expect noerr":
            glyphs[-1].append(l)
    run = lambda steps: subprocess.run(ewt_cmd + ["do", "; ".join(steps)], capture_output=True, text=True)
    out = open(outp, "w")
    r = run(head); out.write(r.stdout + r.stderr)
    for i, g in enumerate(glyphs):
        for attempt in range(2):
            r = run(g)
            txt = r.stdout + r.stderr
            if "WRITE: char" in txt or "WRITE: reject" in txt or "WRITE: edit" in txt:
                break
            print(f"glyph {i}: attempt {attempt} failed: {txt.strip().splitlines()[:1]}", flush=True)
            run(["touch up", "wait 800", "btn short", "wait 300", "goto AppList", "wait 300", "goto Write", "wait 600"])
        out.write(f"== glyph {i}\n" + txt); out.flush()
        if i % 20 == 0: print(f"{i}/{len(glyphs)}", flush=True)


if __name__ == "__main__" and sys.argv[1] == "drive":
    drive(sys.argv[2].split("|"), sys.argv[3], sys.argv[4])


PHRASES = ["hello world", "see you soon", "on my way home", "call me later", "good morning",
           "where are you", "running late", "thank you", "meet at 6", "love you",
           "the quick brown fox", "what time is it", "back in 10", "happy birthday",
           "how are you", "ok sounds good", "just landed", "check the watch"]


def words_ewt(path, writers_per=1, seed=21):
    """Phrases written letter by letter by unseen writers (lower case, as most
    people write), a straight left-to-right stroke for each space."""
    r = np.random.default_rng(seed)
    data = tst()
    writers = sorted({d[2].split("-")[0] for d in data})
    out = []
    for ph in PHRASES:
        for _ in range(writers_per):
            wr = writers[r.integers(len(writers))]
            steps = ["goto Write", "expect screen Write", "long 210 250 5000", "wait 300"]
            for ch in ph:
                if ch == " ":
                    y = int(r.uniform(170, 220)); x0 = int(r.uniform(40, 70)); x1 = int(r.uniform(170, 200))
                    pts = [(x0, y)] + [(x0 + (x1 - x0) * k // 6, y + int(r.normal(0, 1.5))) for k in range(1, 7)]
                    steps += [stroke_step([pts]), "wait 650"]
                    continue
                cands = [d for d in data if d[2].startswith(wr) and d[1] == ch]
                s = cands[r.integers(len(cands))][3]
                steps += [stroke_step(place(s, r)), "wait 650"]
            steps.append("wait 3000")                # let the pause correction run on the last word
            steps.append("show WRITE: (text|correct)")
            out.append({"phrase": ph, "writer": wr, "steps": steps})
    import json
    json.dump(out, open(path, "w"))
    print(len(out), "phrases,", sum(len(o["steps"]) for o in out), "steps")


def drive_words(ewt_cmd, path, outp):
    import json, subprocess, re
    items = json.load(open(path))
    res = []
    for it in items:
        txt = ""
        for attempt in range(2):
            r = subprocess.run(ewt_cmd + ["do", "; ".join(it["steps"])], capture_output=True, text=True)
            txt = r.stdout + r.stderr
            if "PASS" in txt:
                break
            print("   attempt", attempt, "failed:", (txt.strip().splitlines() or ["?"])[0][:150], flush=True)
            subprocess.run(ewt_cmd + ["do", "touch up; wait 800"], capture_output=True, text=True)
        # The final text, asked for directly (log lines can be lost over USB).
        got = "<none>"
        for _ in range(4):
            q = subprocess.run(ewt_cmd + ["raw", "write text", "-t", "1"], capture_output=True, text=True).stdout
            m = re.search(r"WTEXT:(.*)\|", q)
            if m:
                got = m.group(1).strip()
                break
        corr = re.findall(r"WRITE: correct from=(\S+) to=(\S+)", txt)
        res.append((it["phrase"], got, it["writer"], corr, "PASS" in txt))
        print(f"{'OK ' if got == it['phrase'] else '   '} want={it['phrase']!r:24} got={got!r:24} {it['writer']} fixes={corr}", flush=True)
    n = len(res)
    exact = sum(g == p for p, g, *_ in res)
    def ed(a, b):
        d = list(range(len(b) + 1))
        for i, ca in enumerate(a, 1):
            p, d[0] = d[0], i
            for j, cb in enumerate(b, 1):
                p, d[j] = d[j], min(d[j] + 1, d[j - 1] + 1, p + (ca != cb))
        return d[-1]
    cer = sum(ed(p, g) for p, g, *_ in res) / sum(len(p) for p, *_ in res)
    wa = [sum(a == b for a, b in zip(p.split(), g.split())) for p, g, *_ in res]
    wt = sum(len(p.split()) for p, *_ in res)
    print(f"phrases exact {exact}/{n}  words right {sum(wa)}/{wt} = {sum(wa)/wt:.3f}  char error rate {cer:.3f}")
    open(outp, "w").write("\n".join(f"{p}\t{g}\t{w}\t{c}" for p, g, w, c, _ in res) + "\n")


if __name__ == "__main__" and sys.argv[1] == "words":
    words_ewt(sys.argv[2])
if __name__ == "__main__" and sys.argv[1] == "drive_words":
    drive_words(sys.argv[2].split("|"), sys.argv[3], sys.argv[4])
