"""Train the motion language model and export it into the firmware.

  tools/.venv/bin/python -m motionlm.train                 # synthetic only
  tools/.venv/bin/python -m motionlm.train --real data/real.jsonl --real-weight 4
  tools/.venv/bin/python -m motionlm.train --init out/motion_lm.pt --steps 1500 --real ...  # fine-tune

Writes:
  tools/out/motion_lm.pt, tools/out/motion_lm.bin (llama2.c format),
  tools/out/report.json (held-out accuracy, confusion),
  src/apps/motion/motion_model_data.c (weights as a const array in flash).
Run from llm_motion/tools.
"""
import argparse
import json
import os
import time

import numpy as np
import torch
import torch.nn.functional as F

from . import dataset as D, vocab as V, tokenizer as T
from .model import Cfg, MotionLM, export_llama2c

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
PROJ = os.path.dirname(TOOLS)
OUT = os.path.join(TOOLS, "out")
DATA = os.path.join(TOOLS, "data")
SRC_MOTION = os.path.join(PROJ, "src", "apps", "motion")
LABEL_W = 4.0


def batchify(items, seq_len):
    B = len(items)
    x = torch.zeros(B, seq_len, dtype=torch.long)
    y = torch.full((B, seq_len), -100, dtype=torch.long)
    w = torch.zeros(B, seq_len)
    for i, (seg, lab) in enumerate(items):
        ids = D.to_ids(seg, lab)[:seq_len + 1]
        n = len(ids) - 1
        x[i, :n] = torch.tensor(ids[:-1])
        y[i, :n] = torch.tensor(ids[1:])
        w[i, :n] = 1.0
        w[i, n - 1] = LABEL_W           # the label prediction (after SEP)
    return x, y, w


@torch.no_grad()
def predict(model, items, seq_len, bs=1024):
    """Returns (pred_label_idx, p_best) using the logits at SEP, restricted
    to label tokens (exactly what the firmware does)."""
    model.eval()
    preds, probs = [], []
    for k in range(0, len(items), bs):
        chunk = items[k:k + bs]
        x, _, _ = batchify(chunk, seq_len)
        logits = model(x)
        for i, (seg, _) in enumerate(chunk):
            pos = len(seg) + 1                       # index of SEP
            lg = logits[i, pos, V.LABEL0:V.VOCAB]
            p = F.softmax(lg, -1)
            j = int(torch.argmax(p))
            preds.append(j)
            probs.append(float(p[j]))
    return np.array(preds), np.array(probs)


def evaluate(model, items, seq_len, thr):
    pred, p = predict(model, items, seq_len)
    gold = np.array([V.LABELS.index(l) for _, l in items])
    final = np.where(p >= thr, pred, 0)
    n = len(V.LABELS)
    conf = np.zeros((n, n), int)
    for g, f in zip(gold, final):
        conf[g, f] += 1
    per = {V.LABELS[i]: (float(conf[i, i] / conf[i].sum()) if conf[i].sum() else None) for i in range(n)}
    pos = gold != 0
    rep = {
        "n": int(len(items)),
        "threshold": thr,
        "accuracy_raw_argmax": float((pred == gold).mean()),
        "accuracy": float((final == gold).mean()),
        "accuracy_gestures_only": float((final[pos] == gold[pos]).mean()),
        "none_false_trigger_rate": float((final[~pos] != 0).mean()) if (~pos).any() else None,
        "gesture_rejected_as_none": float((final[pos] == 0).mean()),
        "per_class_recall": per,
        "confusion_rows_gold_cols_pred": conf.tolist(),
        "labels": V.LABELS,
    }
    return rep


def write_c_array(bin_path, c_path, meta):
    data = open(bin_path, "rb").read()
    assert len(data) % 4 == 0
    words = np.frombuffer(data, "<u4")
    with open(c_path, "w") as f:
        f.write("// GENERATED by tools/motionlm/train.py - do not edit.\n")
        f.write("// Motion language model, llama2.c legacy checkpoint format\n")
        f.write("// (7 x int32 header + fp32 weights), stored as 32-bit words so it is\n")
        f.write("// 4-byte aligned in flash (.rodata) and read in place (no RAM copy).\n")
        for k, v in meta.items():
            f.write("// %s: %s\n" % (k, v))
        f.write('#include <stdint.h>\n#include "motion_lm.h"\n\n')
        f.write("const uint32_t motion_model_words[%d] = {\n" % len(words))
        for i in range(0, len(words), 8):
            f.write("  " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",\n")
        f.write("};\nconst uint32_t motion_model_nwords = %d;\n" % len(words))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dim", type=int, default=32)
    ap.add_argument("--hidden", type=int, default=64)
    ap.add_argument("--layers", type=int, default=2)
    ap.add_argument("--heads", type=int, default=4)
    ap.add_argument("--steps", type=int, default=4000)
    ap.add_argument("--bs", type=int, default=128)
    ap.add_argument("--lr", type=float, default=3e-3)
    ap.add_argument("--n", type=int, default=4000, help="segments per IMU gesture class")
    ap.add_argument("--n-none", type=int, default=14000)
    ap.add_argument("--n-touch", type=int, default=800)
    ap.add_argument("--thr", type=float, default=0.6)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--regen", action="store_true")
    ap.add_argument("--real", default=None, help="jsonl of real labelled segments (capture_to_dataset.py)")
    ap.add_argument("--real-weight", type=int, default=4, help="oversample real data this many times")
    ap.add_argument("--init", default=None, help="fine-tune from this .pt")
    ap.add_argument("--no-firmware", action="store_true", help="don't overwrite motion_model_data.c")
    ap.add_argument("--outdir", default=OUT, help="where the .pt/.bin/report.json go")
    a = ap.parse_args()

    torch.manual_seed(a.seed)
    os.makedirs(a.outdir, exist_ok=True)
    os.makedirs(DATA, exist_ok=True)
    paths = {k: os.path.join(DATA, "synth_%s.jsonl" % k) for k in ("train", "val", "test")}
    if a.regen or not all(os.path.exists(p) for p in paths.values()):
        t0 = time.time()
        sizes = {"train": (a.n, a.n_none, a.n_touch), "val": (400, 1400, 100), "test": (1000, 3500, 200)}
        seeds = {"train": a.seed * 11 + 1, "val": a.seed * 11 + 2, "test": a.seed * 11 + 3}
        allstats = {}
        for k in ("train", "val", "test"):
            d, st = D.build(*sizes[k], seed=seeds[k])
            D.save_jsonl(paths[k], d)
            allstats[k] = st
            print("built %s: %d sequences" % (k, len(d)))
        json.dump(allstats, open(os.path.join(DATA, "build_stats.json"), "w"), indent=1)
        print("data built in %.0f s" % (time.time() - t0))
    train = D.load_jsonl(paths["train"])
    val = D.load_jsonl(paths["val"])
    test = D.load_jsonl(paths["test"])
    real_test = []
    if a.real:
        real = D.load_jsonl(a.real)
        rng = np.random.default_rng(0)
        idx = rng.permutation(len(real))
        cut = int(len(real) * 0.8)
        real_train = [real[i] for i in idx[:cut]]
        real_test = [real[i] for i in idx[cut:]]
        train = train + real_train * a.real_weight
        print("real data: %d train (x%d) / %d held out" % (len(real_train), a.real_weight, len(real_test)))

    cfg = Cfg(dim=a.dim, hidden_dim=a.hidden, n_layers=a.layers, n_heads=a.heads,
              vocab_size=V.VOCAB, seq_len=T.SEQ_LEN)
    if a.init:                      # fine-tune: architecture comes from the checkpoint
        ck = torch.load(a.init)
        cfg = Cfg(**ck["cfg"])
    model = MotionLM(cfg)
    if a.init:
        model.load_state_dict(ck["model"])
    print("params:", model.n_params())
    opt = torch.optim.AdamW(model.parameters(), lr=a.lr, weight_decay=0.01, betas=(0.9, 0.98))
    rng = np.random.default_rng(a.seed)
    t0 = time.time()
    best = (-1, None)
    for step in range(1, a.steps + 1):
        lr = a.lr * min(1.0, step / 200) * (0.5 * (1 + np.cos(np.pi * step / a.steps)) * 0.95 + 0.05)
        for g in opt.param_groups:
            g["lr"] = lr
        model.train()
        idx = rng.integers(0, len(train), a.bs)
        x, y, w = batchify([train[i] for i in idx], cfg.seq_len)
        logits = model(x)
        loss = F.cross_entropy(logits.view(-1, cfg.vocab_size), y.view(-1), reduction="none", ignore_index=-100)
        loss = (loss * w.view(-1)).sum() / w.sum()
        opt.zero_grad()
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        opt.step()
        if step % 500 == 0 or step == a.steps:
            r = evaluate(model, val, cfg.seq_len, a.thr)
            print("step %5d loss %.4f val acc %.4f (gest %.4f, none FP %.4f) %.0fs" % (
                step, loss.item(), r["accuracy"], r["accuracy_gestures_only"],
                r["none_false_trigger_rate"], time.time() - t0))
            if r["accuracy"] > best[0]:
                best = (r["accuracy"], {k: v.clone() for k, v in model.state_dict().items()})
    model.load_state_dict(best[1])
    rep = {"config": cfg.__dict__, "params": model.n_params(), "train_sequences": len(train),
           "test_synthetic": evaluate(model, test, cfg.seq_len, a.thr)}
    if real_test:
        rep["test_real_heldout"] = evaluate(model, real_test, cfg.seq_len, a.thr)
    ckpt = os.path.join(a.outdir, "motion_lm.pt")
    torch.save({"model": model.state_dict(), "cfg": cfg.__dict__}, ckpt)
    binp = os.path.join(a.outdir, "motion_lm.bin")
    export_llama2c(model, binp)
    rep["bin_bytes"] = os.path.getsize(binp)
    json.dump(rep, open(os.path.join(a.outdir, "report.json"), "w"), indent=1)
    ts = rep["test_synthetic"]
    print("TEST (synthetic, held-out seed): acc %.4f  gestures %.4f  none-FP %.4f  rejected %.4f" % (
        ts["accuracy"], ts["accuracy_gestures_only"], ts["none_false_trigger_rate"], ts["gesture_rejected_as_none"]))
    for k, v in ts["per_class_recall"].items():
        print("  %-13s %.4f" % (k, v))
    if not a.no_firmware:
        meta = {"params": model.n_params(), "dim": cfg.dim, "hidden_dim": cfg.hidden_dim,
                "n_layers": cfg.n_layers, "n_heads": cfg.n_heads, "vocab": cfg.vocab_size,
                "seq_len": cfg.seq_len, "synthetic_test_accuracy": round(ts["accuracy"], 4),
                "trained": time.strftime("%Y-%m-%d %H:%M")}
        write_c_array(binp, os.path.join(SRC_MOTION, "motion_model_data.c"), meta)
        print("wrote", os.path.join(SRC_MOTION, "motion_model_data.c"))


if __name__ == "__main__":
    main()
