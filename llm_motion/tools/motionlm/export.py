"""Export helpers.

  python -m motionlm.export weights out/motion_lm.bin      # -> src/apps/motion/motion_model_data.c
  python -m motionlm.export traces                         # -> src/apps/motion/motion_traces.c

The canned traces back the `motion inject <class> [variant]` console command:
synthetic traces from a seed (777) that is NOT used for train/val/test, NOT
filtered by what the model gets right. They are replayed through the same
sample -> tokenizer -> segmenter -> LM path as the live accelerometer.
"""
import json
import os
import sys

import numpy as np

from . import synth, vocab as V
from .train import write_c_array, SRC_MOTION, OUT

N_VAR = 3
TRACE_SEED = 777


def export_traces():
    rng = np.random.default_rng(TRACE_SEED)
    rows, index = [], []
    for ci, name in enumerate(V.IMU_LABELS):
        for v in range(N_VAR):
            tr = synth.gen(name, rng)
            index.append((ci, v, len(rows), len(tr)))
            rows.extend(tr.tolist())
    path = os.path.join(SRC_MOTION, "motion_traces.c")
    with open(path, "w") as f:
        f.write("// GENERATED by tools/motionlm/export.py traces - do not edit.\n")
        f.write("// Synthetic IMU traces (raw counts, 50 Hz) for `motion inject`.\n")
        f.write("// seed %d (held out from training), %d variants per class, unfiltered.\n" % (TRACE_SEED, N_VAR))
        f.write('#include "motion_traces.h"\n\n')
        f.write("const int16_t kMotionTraceSamples[%d][3] = {\n" % len(rows))
        for r in rows:
            f.write("  {%d,%d,%d},\n" % tuple(r))
        f.write("};\n\nconst MotionTraceRef kMotionTraces[%d] = {\n" % len(index))
        for ci, v, off, n in index:
            f.write("  {%d, %d, %d, %d},   // %s v%d\n" % (ci, v, off, n, V.IMU_LABELS[ci], v))
        f.write("};\nconst int kMotionTraceCount = %d;\n" % len(index))
    json.dump({"seed": TRACE_SEED, "index": index, "samples": rows},
              open(os.path.join(OUT, "inject_traces.json"), "w"))
    print("wrote", path, len(index), "traces,", len(rows), "samples")


def main():
    if len(sys.argv) >= 3 and sys.argv[1] == "weights":
        binp = sys.argv[2]
        rep = json.load(open(os.path.join(OUT, "report.json")))
        meta = {"params": rep["params"], "config": rep["config"],
                "synthetic_test_accuracy": round(rep["test_synthetic"]["accuracy"], 4)}
        write_c_array(binp, os.path.join(SRC_MOTION, "motion_model_data.c"), meta)
        print("wrote motion_model_data.c from", binp)
    elif len(sys.argv) >= 2 and sys.argv[1] == "traces":
        export_traces()
    else:
        print(__doc__)


if __name__ == "__main__":
    main()
