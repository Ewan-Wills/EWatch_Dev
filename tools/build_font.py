#!/usr/bin/env python3
"""Rasterise Space Grotesk (OFL, tools/SpaceGrotesk.ttf) into anti-aliased
8-bit alpha glyphs for the clock: src/font_data.h.

  BIG   - Bold, digits, ":" and "-" for HH:MM and --:--
  SMALL - Medium, capitals, digits and space for the date and layer label

  uv run --with pillow tools/build_font.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
TTF = HERE / "SpaceGrotesk.ttf"
OUT = HERE.parent / "src/font_data.h"

FONTS = [
    ("BIG", 60, 700, "0123456789:-"),
    ("SMALL", 13, 560, " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"),
]

lines = ["// Auto-generated by tools/build_font.py from Space Grotesk (SIL OFL 1.1). Do not edit.",
         "#pragma once", "#include <stdint.h>", "",
         "struct AAGlyph { char ch; int8_t x, y; uint8_t w, h, adv; uint32_t off; };  // y: top, from the baseline",
         "struct AAFont { const AAGlyph *glyphs; uint8_t count; const uint8_t *alpha; uint8_t ascent, digitAdv; };", ""]
for name, size, wght, chars in FONTS:
    f = ImageFont.truetype(str(TTF), size)
    f.set_variation_by_axes([wght])
    alpha, glyphs = bytearray(), []
    for ch in chars:
        adv = round(f.getlength(ch))
        l, t, r, b = f.getbbox(ch, anchor="ls") if ch != " " else (0, 0, 0, 0)
        w, h = r - l, b - t
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor="ls")
            data = im.tobytes()
        else:
            data = b""
        glyphs.append((ch, l, t, w, h, adv, len(alpha)))
        alpha += data
    asc = -min(g[2] for g in glyphs)
    dadv = max(g[5] for g in glyphs if g[0].isdigit())
    lines.append(f"static const uint8_t {name}_ALPHA[] = {{")
    for i in range(0, len(alpha), 40):
        lines.append("".join(f"{x}," for x in alpha[i:i+40]))
    lines.append("};")
    lines.append(f"static const AAGlyph {name}_GLYPHS[] = {{")
    for ch, l, t, w, h, adv, off in glyphs:
        lines.append(f"  {{'{ch}', {l}, {t}, {w}, {h}, {adv}, {off}}},")
    lines.append("};")
    lines.append(f"static const AAFont FONT_{name} = {{{name}_GLYPHS, {len(glyphs)}, {name}_ALPHA, {asc}, {dadv}}};")
    lines.append("")
    print(f"{name}: {len(glyphs)} glyphs, {len(alpha)} B alpha, ascent {asc}, digit advance {dadv}")
OUT.write_text("\n".join(lines) + "\n")
print("wrote", OUT)
