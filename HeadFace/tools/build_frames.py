#!/usr/bin/env python3
"""Pack the turning CT head into src/frames_data.h as baseline JPEGs.

Input: the Blender turntable renders (render_head.py in
~/Documents/ewan-ct-scan/watchface): <layer>_<f:03d>.png, RGBA 240x280, one
full turn of FRAMES_PER_TURN frames for each layer.

The loop is four turns: skin, skull, brain, ventricles, then back to skin.
Over the last WIPE frames of each turn a glowing scan plane sweeps down the
head: above it the next layer, below it the current one (both at the same
angle, so the turn never stops). Every frame is composited on black and
JPEG-encoded at ONE shared quality, the highest that fits BUDGET bytes.

  uv run --with pillow --with numpy tools/build_frames.py [renders_dir] [--budget N]
"""
import argparse, io, sys
from pathlib import Path
import numpy as np
from PIL import Image

LAYERS = ["skin", "skull", "brain", "ventricles"]
W, H = 240, 280

ap = argparse.ArgumentParser()
ap.add_argument("renders", nargs="?", default=str(Path.home() / "Documents/ewan-ct-scan/watchface/renders"))
ap.add_argument("--turn", type=int, default=96, help="frames per full turn (as rendered)")
ap.add_argument("--wipe", type=int, default=30, help="frames of each turn spent wiping to the next layer")
ap.add_argument("--budget", type=int, default=3_700_000, help="bytes of JPEG data")
ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "src/frames_data.h"))
ap.add_argument("--preview", default="", help="also write the composited frames as PNGs here")
a = ap.parse_args()

def load(layer, f):
    p = Path(a.renders) / f"{layer}_{f:03d}.png"
    return np.asarray(Image.open(p).convert("RGBA"), dtype=np.float32) / 255.0

def over_black(rgba):
    return rgba[..., :3] * rgba[..., 3:4]            # Blender PNGs are straight alpha

def extent(*imgs):
    """Rows covered by any of the images' alpha (for the wipe's start/end)."""
    rows = np.where(np.max([i[..., 3].max(axis=1) for i in imgs], axis=0) > 0.02)[0]
    return (int(rows[0]), int(rows[-1])) if len(rows) else (0, H - 1)

GLOW = np.array([0.35, 0.85, 1.0], np.float32)         # cyan scan plane

def wipe(cur, nxt, p):
    """p 0..1: scan line from the top of both heads to the bottom."""
    y0, y1 = extent(cur, nxt)
    y0, y1 = y0 - 4, y1 + 4
    ly = y0 + (y1 - y0) * p
    ys = np.arange(H, dtype=np.float32)[:, None]
    k = np.clip((ly - ys) / 2.0 + 0.5, 0, 1)[..., None]    # 1 above the line (2 px feather)
    img = over_black(nxt) * k + over_black(cur) * (1 - k)
    # The plane lights up where it cuts either head, plus a faint full-width hairline.
    alpha = np.maximum(cur[..., 3], nxt[..., 3])[..., None]
    d = (ys - ly)[..., None]
    core = np.exp(-(d / 1.1) ** 2)
    halo = np.exp(-(d / 5.0) ** 2) * 0.45
    img = img + GLOW * (core * (0.25 + 0.75 * alpha) + halo * alpha)
    return np.clip(img, 0, 1)

frames, layer_of = [], []
for k, layer in enumerate(LAYERS):
    nxt_layer = LAYERS[(k + 1) % len(LAYERS)]
    for f in range(a.turn):
        cur = load(layer, f)
        into = f - (a.turn - a.wipe)                  # 0..wipe-1 inside the wipe
        if into >= 0:
            p = (into + 1) / a.wipe                   # last frame of the turn = fully next layer
            img = wipe(cur, load(nxt_layer, f), p)
            shown = (k + 1) % len(LAYERS) if p >= 0.5 else k
        else:
            img, shown = over_black(cur), k
        frames.append(Image.fromarray((img * 255 + 0.5).astype(np.uint8), "RGB"))
        layer_of.append(shown)
    print(f"{layer}: {a.turn} frames")

if a.preview:
    Path(a.preview).mkdir(parents=True, exist_ok=True)
    for i, im in enumerate(frames):
        im.save(Path(a.preview) / f"frame_{i:03d}.png")

def encode(q):
    out = []
    for im in frames:
        b = io.BytesIO()
        im.save(b, "JPEG", quality=q, optimize=True, progressive=False, subsampling=2)
        out.append(b.getvalue())
    return out

lo, hi, best = 20, 95, None
while lo <= hi:                                       # highest quality that fits
    q = (lo + hi) // 2; enc = encode(q); total = sum(map(len, enc))
    print(f"  q={q}: {total/1e6:.2f} MB")
    if total <= a.budget: best = (q, enc); lo = q + 1
    else: hi = q - 1
if not best:
    sys.exit("does not fit even at q=20; render fewer frames per turn")
q, enc = best

blob, index = bytearray(), []
for i, e in enumerate(enc):
    index.append((len(blob), len(e), layer_of[i])); blob += e

with open(a.out, "w") as f:
    f.write("// Auto-generated by tools/build_frames.py from the CT head turntable renders. Do not edit.\n")
    f.write(f"// {len(index)} frames ({len(LAYERS)} turns x {a.turn}, {a.wipe}-frame wipes), 240x280 baseline JPEG, quality {q}, {len(blob)} bytes.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write("struct HeadFrame { uint32_t off; uint32_t len; uint8_t layer; };\n")
    f.write(f"static const uint16_t FRAME_COUNT = {len(index)};\n")
    f.write(f"static const uint16_t FRAMES_PER_TURN = {a.turn};\n")
    f.write(f"static const uint8_t LAYER_COUNT = {len(LAYERS)};\n")
    f.write("static const char *const LAYER_NAMES[] = {" + ", ".join(f'"{l.upper()}"' for l in LAYERS) + "};\n")
    f.write("static const uint8_t FRAME_JPEG[] = {\n")
    for i in range(0, len(blob), 32):
        f.write("".join(f"{x}," for x in blob[i:i+32]) + "\n")
    f.write("};\nstatic const HeadFrame FRAMES[] = {\n")
    for off, ln, l in index:
        f.write(f"  {{{off}, {ln}, {l}}},\n")
    f.write("};\n")
print(f"wrote {a.out}: {len(index)} frames, q={q}, {len(blob)/1e6:.2f} MB, avg {len(blob)//len(index)} B")
